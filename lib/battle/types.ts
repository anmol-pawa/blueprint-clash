/** Card battle model (GDD §5.1). Pure data: no rendering, no DOM. */

interface CardBase {
  id: string;
  /** Short lesson / topic tag, e.g. "raii". */
  topic: string;
  /** Shown after an answer, correct or not. */
  explain: string;
}

export interface McqCard extends CardBase {
  kind: "mcq";
  prompt: string;
  options: string[];
  answer: number;
}

export interface MultiCard extends CardBase {
  kind: "multi";
  prompt: string;
  options: string[];
  /** Indices of every correct option; the response must match the set exactly. */
  answers: number[];
}

/** A scenario → the pattern that fits (options are Patternling pattern names). */
export interface PatternCard extends CardBase {
  kind: "pattern";
  scenario: string;
  options: string[];
  answer: number;
}

/** A C++ snippet → name the smell / violated principle. */
export interface SmellCard extends CardBase {
  kind: "smell";
  code: string;
  options: string[];
  answer: number;
}

/** A C++ snippet → what does it print. `output` is generated by running it natively. */
export interface PredictCard extends CardBase {
  kind: "predict";
  code: string;
  options: string[];
  answer: number;
}

export type Card = McqCard | MultiCard | PatternCard | SmellCard | PredictCard;

/** Player response: the chosen option index, or the set of chosen indices for a multi-select. */
export type Response = number | number[];

export interface PredictSource {
  id: string;
  topic: string;
  /** Complete program; its stdout is the correct answer. */
  code: string;
  /** Plausible wrong outputs. Must differ from the real output (verified). */
  distractors: string[];
  explain: string;
}
